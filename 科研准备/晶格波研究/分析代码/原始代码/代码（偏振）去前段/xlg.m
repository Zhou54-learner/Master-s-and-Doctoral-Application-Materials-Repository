function [xx,yy,vxx,vyy] = xlg(x,y,vx,vy,dt,x01,x02,x03,x04,x05,x06,y01,y02,y03,y04,y05,y06,q0,q1,q2,q3,q4,q5,q6,k,m,b)
x1=zeros(2,2);
x1(1,1)=x;
x1(1,2)=y;
x1(2,1)=vx;
x1(2,2)=vy;
g1=zeros(2,2);
g1(1,1)=vx;
g1(1,2)=vy;
g1(2,1)=vxnn(x,x01,x02,x03,x04,x05,x06,y,y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*g1(1,1);
g1(2,2)=vynn(x,x01,x02,x03,x04,x05,x06,y,y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*g1(1,2);
k1=g1;
x2=x1+(dt./2)*k1;
k2=zeros(2,2);
k2(1,1)=x2(2,1);
k2(1,2)=x2(2,2);
k2(2,1)=vxnn(x2(1,1),x01,x02,x03,x04,x05,x06,x2(1,2),y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*k2(1,1);
k2(2,2)=vynn(x2(1,1),x01,x02,x03,x04,x05,x06,x2(1,2),y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*k2(1,2);
x3=x2+(dt./2)*k2;
k3=zeros(2,2);
k3(1,1)=x3(2,1);
k3(1,2)=x3(2,2);
k3(2,1)=vxnn(x3(1,1),x01,x02,x03,x04,x05,x06,x3(1,2),y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*k3(1,1);
k3(2,2)=vynn(x3(1,1),x01,x02,x03,x04,x05,x06,x3(1,2),y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*k3(1,2);
x4=x3+dt*k3;
k4=zeros(2,2);
k4(1,1)=x4(2,1);
k4(1,2)=x4(2,2);
k4(2,1)=vxnn(x4(1,1),x01,x02,x03,x04,x05,x06,x4(1,2),y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*k4(1,1);
k4(2,2)=vynn(x4(1,1),x01,x02,x03,x04,x05,x06,x4(1,2),y01,y02,y03,y04,y05,y06,0,dt,k,q0,q1,q2,q3,q4,q5,q6,m,0)./dt-b.*k4(1,2);
x1=x1+(dt./6)*(k1+2*k2+2*k3+k4);
xx=x1(1,1);
yy=x1(1,2);
vxx=x1(2,1);
vyy=x1(2,2);
end

